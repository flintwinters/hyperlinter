"""Compile authored StyleX into static HTML/CSS; published pages need no JavaScript."""
import json
import re
import subprocess
from html.parser import HTMLParser


class Template(HTMLParser):
    def __init__(self, source):
        super().__init__(convert_charrefs=False)
        self.source = source
        self.requests = []
        self.edits = []
        self.offsets = [0]
        for line in source.splitlines(keepends=True):
            self.offsets.append(self.offsets[-1] + len(line))
        self.feed(source)

    def handle_starttag(self, tag, attributes):
        if tag in {'head', 'meta', 'link', 'title', 'script'}:
            return
        names = dict(attributes).get('class', '').split()
        self.requests.append({'tag': tag, 'names': names})
        line, column = self.getpos()
        offset = self.offsets[line - 1] + column
        self.edits.append((offset, self.get_starttag_text(), names))


def build_site(root, check=False):
    source = (root / 'scripts/site/template.html').read_text()
    template = Template(source)
    result = subprocess.run(['node', 'scripts/site/compile.mjs'], cwd=root,
                            input=json.dumps(template.requests), capture_output=True, text=True)
    if result.returncode:
        raise ValueError(f'StyleX compilation failed:\n{result.stderr}')
    compiled = json.loads(result.stdout)
    for (offset, original, names), classes in reversed(list(zip(template.edits, compiled['classes']))):
        attribute = f'class="{" ".join([*names, classes])}"'
        updated = re.sub(r'class="[^"]*"', lambda _: attribute, original) if names else original[:-1] + ' ' + attribute + '>'
        source = source[:offset] + updated + source[offset + len(original):]
    files = {'docs/index.html': source, 'docs/dist/site.css': '/* Generated by manage.py site-build from StyleX. */\n' + compiled['css'] + '\n'}
    for name, content in files.items():
        target = root / name
        if check:
            if not target.exists() or target.read_text() != content:
                raise ValueError(f'Stale generated site asset: {name}; run python3 manage.py site-build.')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
